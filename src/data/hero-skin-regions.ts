/** Håndtegnede materialmasker for de malte delene. Koordinater gjelder ferdig beskåret bilde.
 * Polygonene avgrenser hud; fargeporten i tegneren finjusterer innsiden, aldri utsiden.
 * Tom include betyr at delen er kontrollert og ikke har hud. Ukjente bilder skal ikke tones.
 * Ved utskifting av et bilde må områdene kontrolleres på nytt, som leddpunktene i manifestet.
 */
export type SkinFamily = 'warm' | 'olive' | 'frost';
export type SkinPoint = readonly [number, number];
export type SkinPolygon = readonly SkinPoint[];
export interface HeroSkinRegions {
  family: SkinFamily;
  include: readonly SkinPolygon[];
  exclude?: readonly SkinPolygon[];
  /** Skjeggdetaljer: mørke varme strå og nøytrale froststrå vernes; huden mellom dem tones. */
  hairDetail?: readonly SkinPolygon[];
  /** Omtrentlig mellomtone i originalhuden; lys og tekstur beholdes ved fargebytte. */
  reference?: string;
}

// Prosent gjør håndmålte kurver leselige. Resultatet er alltid normaliserte koordinater.
const p = (...xy: number[]): SkinPolygon => {
  const points: SkinPoint[] = [];
  for (let i = 0; i < xy.length; i += 2) points.push([xy[i] / 100, xy[i + 1] / 100]);
  return points;
};
